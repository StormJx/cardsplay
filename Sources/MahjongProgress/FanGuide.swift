import MahjongRules

public struct FanGuide: Identifiable, Sendable {
  public let fan: Fan
  public let summary: String
  public let limit: String
  public let example: String
  public let pitfall: String
  public let excluded: [Fan]

  public var id: Int { fan.rawValue }
  public var points: Int { fan.points }
  public var name: String { fan.name }

  public var excludedNames: String {
    let names = excluded.map(\.name)
    return names.isEmpty ? "无单独列出的不计项" : names.joined(separator: "、")
  }
}

public enum FanGuideBook {
  public static let all: [FanGuide] = Fan.allCases.map { fan in
    let row = rows[fan.rawValue - 1]
    let excluded = (MCRRuleBook.definitions[fan]?.excludedFans ?? []).sorted {
      $0.rawValue < $1.rawValue
    }
    return FanGuide(
      fan: fan,
      summary: row.summary,
      limit: row.limit,
      example: row.example,
      pitfall: row.pitfall,
      excluded: excluded
    )
  }

  public static func guide(_ fan: Fan) -> FanGuide {
    all[fan.rawValue - 1]
  }

  public static func timesAchieved(_ fan: Fan, records: [HandRecord]) -> Int {
    records.filter { $0.humanWon && $0.awardFans.contains(fan.rawValue) }.count
  }

  public static func bestRecord(for fan: Fan, records: [HandRecord]) -> HandRecord? {
    records.filter { $0.canReplay && $0.humanWon && $0.awardFans.contains(fan.rawValue) }
      .max { lhs, rhs in
        if lhs.fanPoints != rhs.fanPoints { return lhs.fanPoints < rhs.fanPoints }
        return lhs.playedAt > rhs.playedAt
      }
  }

